import cors from "cors";
import express from "express";
import helmet from "helmet";
import { env } from "./config/env.js";
import { notFound } from "./middleware/notFound.js";
import { errorHandler } from "./middleware/errorHandler.js";
import healthRoutes from "./modules/health/health.routes.js";
import bookRoutes from "./modules/books/books.routes.js";
import authRoutes from "./modules/auth/auth.routes.js";
import wishlistRoutes from "./modules/wishlist/wishlist.routes.js";
import followsRoutes from "./modules/auth/follows.routes.js";
import reviewModerationRoutes from "./modules/books/review-moderation.routes.js";
import authorApplicationsRoutes from "./modules/auth/author-applications.routes.js";
import authorRoutes from "./modules/auth/author.routes.js";
import publicAuthorsRoutes from "./modules/auth/public-authors.routes.js";
import authorAdminRoutes from "./modules/auth/author-admin.routes.js";
import authorBookAdminRoutes from "./modules/books/author-book-admin.routes.js";
import adminDashboardRoutes from "./modules/admin/admin.routes.js";
import adminUsersRoutes from "./modules/admin/admin-users.routes.js";
import authorManagementRoutes from "./modules/auth/author-management.routes.js";
import catalogueAdminRoutes from "./modules/books/catalogue-admin.routes.js";
import categoriesRoutes from "./modules/books/categories.routes.js";
import adminCategoriesRoutes from "./modules/books/admin-categories.routes.js";
import cmsPagesRoutes from "./modules/cms/cms-pages.routes.js";
import adminCmsPagesRoutes from "./modules/cms/admin-cms-pages.routes.js";
import siteSettingsRoutes from "./modules/cms/site-settings.routes.js";
import adminSiteSettingsRoutes from "./modules/cms/admin-site-settings.routes.js";

const app = express();
app.disable("x-powered-by");
app.use(helmet({ contentSecurityPolicy: { directives: { imgSrc: ["\u0027self\u0027", "data:", "https:"] } } }));
app.use(cors({ origin: env.clientOrigin, credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.get("/", (_request, response) => response.json({ name: "Rasbhav Books API", version: "v1" }));
app.use("/api/v1/health", healthRoutes);
app.use("/api/v1/books", bookRoutes);
app.use("/api/v1/categories", categoriesRoutes);
app.use("/api/v1/pages", cmsPagesRoutes);
app.use("/api/v1/site-content", siteSettingsRoutes);
app.use("/api/v1/auth", authRoutes);
app.use("/api/v1/wishlist", wishlistRoutes);
app.use("/api/v1/reader/follows", followsRoutes);
app.use("/api/v1/admin/reviews", reviewModerationRoutes);
app.use("/api/v1/author-applications", authorApplicationsRoutes);
app.use("/api/v1/author", authorRoutes);
app.use("/api/v1/authors", publicAuthorsRoutes);
app.use("/api/v1/admin/author-applications", authorAdminRoutes);
app.use("/api/v1/admin/author-books", authorBookAdminRoutes);
app.use("/api/v1/admin/dashboard", adminDashboardRoutes);
app.use("/api/v1/admin/users", adminUsersRoutes);
app.use("/api/v1/admin/authors", authorManagementRoutes);
app.use("/api/v1/admin/catalogue-books", catalogueAdminRoutes);
app.use("/api/v1/admin/categories", adminCategoriesRoutes);
app.use("/api/v1/admin/cms-pages", adminCmsPagesRoutes);
app.use("/api/v1/admin/site-settings", adminSiteSettingsRoutes);
app.use(notFound);
app.use(errorHandler);

export default app;
